-- AuraGoal on Supabase, part 8: goal pages. Run after shared_wallpaper.sql.
--   * goal_pages: each of your goals can open into a page: why it matters, and notes made of blocks (text, headings,
--     to-dos, bullets, quotes, callouts, dividers). Private to you, like the goal itself.
--   * team_goal_pages and team_goal_comments: a shared goal's page, which both partners edit, and its discussion.
--     Like the other shared-goal tables they have no grants: the app goes through the functions below, which check
--     that the caller is one of the two partners.
-- Blocks are stored as a JSON array: [{ "id": "...", "type": "p|h|todo|bullet|quote|callout|divider", "text": "...",
-- "done": true|false }]. The app keeps them small; the database caps the size.

create function private.touch_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin new.updated_at := now(); return new; end $$;

-- ---- Your own goals ----
create table public.goal_pages (
  goal_id    bigint primary key references public.goals (id) on delete cascade,
  user_id    uuid not null default auth.uid() references auth.users (id) on delete cascade,
  why        text check (char_length(why) <= 2000),
  blocks     jsonb not null default '[]'::jsonb check (jsonb_typeof(blocks) = 'array' and octet_length(blocks::text) <= 200000),
  updated_at timestamptz not null default now()
);
alter table public.goal_pages enable row level security;
revoke all on public.goal_pages from public, anon, authenticated;
grant select, delete on public.goal_pages to authenticated;
grant insert (goal_id, why, blocks) on public.goal_pages to authenticated;
grant update (why, blocks) on public.goal_pages to authenticated;
create policy "own" on public.goal_pages for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid())
    and exists (select 1 from public.goals g where g.id = goal_id and g.user_id = (select auth.uid())));
create trigger goal_pages_touch before update on public.goal_pages for each row execute function private.touch_updated_at();

-- ---- Shared goals ----
create table public.team_goal_pages (
  team_goal_id bigint primary key references public.team_goals (id) on delete cascade,
  blocks       jsonb not null default '[]'::jsonb check (jsonb_typeof(blocks) = 'array' and octet_length(blocks::text) <= 200000),
  updated_by   uuid references auth.users (id) on delete set null,
  updated_at   timestamptz not null default now()
);
create table public.team_goal_comments (
  id           bigint generated by default as identity primary key,
  team_goal_id bigint not null references public.team_goals (id) on delete cascade,
  author_id    uuid not null references auth.users (id) on delete cascade,
  team_plan_id bigint references public.team_plans (id) on delete set null,   -- a comment about one plan, or null
  body         text not null check (char_length(btrim(body)) between 1 and 2000),
  created_at   timestamptz not null default now()
);
create index idx_team_comments_goal on public.team_goal_comments (team_goal_id, id);
alter table public.team_goal_pages enable row level security;
alter table public.team_goal_comments enable row level security;
revoke all on public.team_goal_pages, public.team_goal_comments from public, anon, authenticated;

/** The shared goal, if the caller is one of its two partners (otherwise an error). */
create function private.my_team_goal(p_goal bigint) returns public.team_goals
language plpgsql stable security definer set search_path = '' as $$
declare g public.team_goals;
begin
  select * into g from public.team_goals where id = p_goal;
  if not found then raise exception 'Shared goal not found.'; end if;
  perform private.accepted_partnership(g.partnership_id);
  return g;
end $$;

/**
 * Everything a shared goal's page shows: the goal (with its plans), the notes, the discussion, and the activity
 * (who ticked what, and when).
 */
create function public.team_goal_page(p_goal bigint) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_me uuid := auth.uid();
  g public.team_goals := private.my_team_goal(p_goal);
  pg public.team_goal_pages;
begin
  select * into pg from public.team_goal_pages where team_goal_id = g.id;
  return jsonb_build_object(
    'goal', private.team_goal_json(g, v_me),
    'partnership_id', g.partnership_id,
    'notes', jsonb_build_object('blocks', coalesce(pg.blocks, '[]'::jsonb), 'updated_at', pg.updated_at,
                                'updated_by_me', pg.updated_by = v_me),
    'comments', (select coalesce(jsonb_agg(jsonb_build_object('id', c.id, 'body', c.body, 'mine', c.author_id = v_me,
                   'plan_id', c.team_plan_id, 'at', c.created_at) order by c.id), '[]'::jsonb)
                 from public.team_goal_comments c where c.team_goal_id = g.id),
    'activity', (select coalesce(jsonb_agg(jsonb_build_object('plan_id', t.id, 'text', t.task, 'mine', m.user_id = v_me,
                   'at', m.done_at) order by m.done_at desc), '[]'::jsonb)
                 from public.team_plan_marks m join public.team_plans t on t.id = m.team_plan_id where t.team_goal_id = g.id));
end $$;

/**
 * Saves the shared notes. p_expected is the updated_at the caller last saw: if the partner saved since, nothing is
 * written and their version comes back as { conflict: true, blocks, updated_at }, so nobody overwrites the other.
 */
create function public.save_team_page(p_goal bigint, p_blocks jsonb, p_expected timestamptz) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  g public.team_goals := private.my_team_goal(p_goal);
  pg public.team_goal_pages;
begin
  if jsonb_typeof(p_blocks) <> 'array' then raise exception 'Notes must be a list of blocks.'; end if;
  select * into pg from public.team_goal_pages where team_goal_id = g.id for update;
  if found and pg.updated_at is distinct from p_expected then
    return jsonb_build_object('conflict', true, 'blocks', pg.blocks, 'updated_at', pg.updated_at);
  end if;
  insert into public.team_goal_pages as t (team_goal_id, blocks, updated_by, updated_at)
  values (g.id, p_blocks, auth.uid(), now())
  on conflict (team_goal_id) do update set blocks = excluded.blocks, updated_by = excluded.updated_by, updated_at = excluded.updated_at
  returning * into pg;
  return jsonb_build_object('conflict', false, 'updated_at', pg.updated_at);
end $$;

/** Adds a comment (optionally about one plan) and says so in the chat, so the partner sees it. */
create function public.add_team_comment(p_goal bigint, p_body text, p_plan bigint default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  g public.team_goals := private.my_team_goal(p_goal);
  v_body text := btrim(coalesce(p_body, ''));
  v_msg bigint;
begin
  if char_length(v_body) = 0 then raise exception 'Write something first.'; end if;
  if char_length(v_body) > 2000 then raise exception 'Keep a comment to 2000 characters.'; end if;
  if p_plan is not null and not exists (select 1 from public.team_plans where id = p_plan and team_goal_id = g.id) then
    raise exception 'That plan is not part of this goal.';
  end if;
  insert into public.team_goal_comments (team_goal_id, author_id, team_plan_id, body) values (g.id, auth.uid(), p_plan, v_body);
  v_msg := private.team_note(g.partnership_id, format('commented on %s %s: “%s”', g.emoji, g.title,
             case when char_length(v_body) > 120 then left(v_body, 117) || '…' else v_body end));
  return public.team_goal_page(g.id) || jsonb_build_object('message_id', v_msg);
end $$;

/** Deletes one of your own comments. */
create function public.delete_team_comment(p_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_goal bigint;
begin
  select team_goal_id into v_goal from public.team_goal_comments where id = p_id and author_id = auth.uid();
  if v_goal is null then raise exception 'Comment not found.'; end if;
  perform private.my_team_goal(v_goal);
  delete from public.team_goal_comments where id = p_id;
  return public.team_goal_page(v_goal);
end $$;

revoke execute on function public.team_goal_page(bigint), public.save_team_page(bigint, jsonb, timestamptz),
  public.add_team_comment(bigint, text, bigint), public.delete_team_comment(bigint) from public, anon;
grant execute on function public.team_goal_page(bigint), public.save_team_page(bigint, jsonb, timestamptz),
  public.add_team_comment(bigint, text, bigint), public.delete_team_comment(bigint) to authenticated;
