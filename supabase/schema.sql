/** Ticks or unticks a goal's plan. Finishing one counts as an active day. */
create function public.set_task_done(p_task bigint, p_done boolean) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_goal bigint;
  v_streak jsonb;
begin
  select s.goal_id into v_goal from public.sub_plans s join public.goals g on g.id = s.goal_id where s.id = p_task and g.user_id = auth.uid();
  if v_goal is null then raise exception 'Task not found.'; end if;
  update public.sub_plans set is_completed = p_done where id = p_task;
  if p_done then v_streak := private.touch_streak(auth.uid()); end if;
  return jsonb_build_object('goal_id', v_goal, 'goal_status', (select status from public.goals where id = v_goal),
    'streak_count', v_streak->'count', 'streak', v_streak, 'progress', private.goal_progress(v_goal));
end $$;

/** Marks one day of a plan DONE or SKIPPED, or null to undo it. Finishing one counts as an active day. */
create function public.mark_day_plan(p_id bigint, p_date date, p_state text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  r public.day_plans;
  v_streak jsonb;
begin
  select * into r from public.day_plans where id = p_id and user_id = auth.uid();
  if not found then raise exception 'Plan not found.'; end if;
  if not private.day_plan_occurs(r.plan_date, r.repeat_rule, r.repeat_days, r.repeat_until, p_date) then
    raise exception 'This plan does not happen on that day.';
  end if;
  if p_state is null then
    delete from public.day_plan_marks where day_plan_id = p_id and on_date = p_date;
  elsif p_state in ('DONE', 'SKIPPED') then
    insert into public.day_plan_marks (day_plan_id, on_date, state) values (p_id, p_date, p_state)
    on conflict (day_plan_id, on_date) do update set state = excluded.state, marked_at = now();
  else
    raise exception 'state must be DONE, SKIPPED or null.';
  end if;
  if p_state = 'DONE' then v_streak := private.touch_streak(auth.uid()); end if;
  return jsonb_build_object('streak', v_streak);
end $$;

/** Records a badge when a goal reaches a higher tier than before, worked out from the database. */
create function public.award_badge(p_goal bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_progress jsonb;
  v_pct integer;
  v_tier text;
  v_rank integer;
  v_best integer;
  v_id bigint;
begin
  perform 1 from public.goals where id = p_goal and user_id = auth.uid() for update;   -- two quick calls cannot both award it
  if not found then raise exception 'Goal not found.'; end if;
  v_progress := private.goal_progress(p_goal);
  v_pct := (v_progress->>'percentage')::integer;
  v_tier := case when v_pct >= 90 then 'GOLD' when v_pct >= 75 then 'SILVER' when v_pct >= 50 then 'BRONZE' else 'NONE' end;
  v_rank := case v_tier when 'GOLD' then 3 when 'SILVER' then 2 when 'BRONZE' then 1 else 0 end;
  select coalesce(max(case reward_badge_tier when 'PLATINUM' then 4 when 'GOLD' then 3 when 'SILVER' then 2 when 'BRONZE' then 1 else 0 end), 0)
    into v_best from public.reviews where goal_id = p_goal;
  if v_rank = 0 or v_rank <= v_best then
    return jsonb_build_object('created', false, 'progress', v_progress);
  end if;
  insert into public.reviews (goal_id, completion_percentage, reward_badge_tier) values (p_goal, v_pct, v_tier) returning id into v_id;
  return jsonb_build_object('created', true, 'review', jsonb_build_object('id', v_id, 'reward_rank', v_rank, 'completion_percentage', v_pct), 'progress', v_progress);
end $$;

/**
 * The Catch up page: several changes, all or nothing. Each action is one of
 *   { kind: "plan", id, op: "move", to } | { kind: "plan", id, op: "skip" | "unskip" }
 *   { kind: "goal", id, op: "move", to | null } | { kind: "goal", id, op: "archive" | "restore" }
 */
create function public.reschedule(p_actions jsonb) returns integer
language plpgsql security definer set search_path = '' as $$
declare
  a jsonb;
  v_id bigint;
  v_day date;
  v_to date;
begin
  if jsonb_typeof(p_actions) <> 'array' or jsonb_array_length(p_actions) not between 1 and 100 then
    raise exception 'Send between 1 and 100 actions.';
  end if;
  for a in select * from jsonb_array_elements(p_actions) loop
    v_id := (a->>'id')::bigint;
    v_to := nullif(a->>'to', '')::date;
    if v_to is not null and v_to not between '2000-01-01' and '2100-12-31' then raise exception 'Invalid date.'; end if;
    if a->>'kind' = 'plan' then
      select plan_date into v_day from public.day_plans where id = v_id and user_id = auth.uid() and repeat_rule = 'NONE';
      if not found then raise exception 'Plan not found.'; end if;
      if a->>'op' = 'move' then
        if v_to is null then raise exception 'A plan needs a day to move to.'; end if;
        update public.day_plans set plan_date = v_to where id = v_id;
        delete from public.day_plan_marks where day_plan_id = v_id;   -- a fresh, undone day
      elsif a->>'op' = 'skip' then
        insert into public.day_plan_marks (day_plan_id, on_date, state) values (v_id, v_day, 'SKIPPED')
        on conflict (day_plan_id, on_date) do update set state = 'SKIPPED';
      elsif a->>'op' = 'unskip' then
        delete from public.day_plan_marks where day_plan_id = v_id and state = 'SKIPPED';
      else
        raise exception 'A plan can be moved, skipped or unskipped.';
      end if;
    elsif a->>'kind' = 'goal' then
      perform 1 from public.goals where id = v_id and user_id = auth.uid();
      if not found then raise exception 'Goal not found.'; end if;
      if a->>'op' = 'move' then
        update public.goals set due_date = v_to where id = v_id;
      elsif a->>'op' = 'archive' then
        update public.goals set status = 'ARCHIVED' where id = v_id;
      elsif a->>'op' = 'restore' then
        update public.goals set status = 'ACTIVE' where id = v_id and status = 'ARCHIVED';
      else
        raise exception 'A goal can be moved, archived or restored.';
      end if;
    else
      raise exception 'Every action needs a kind, an op and an id.';
    end if;
  end loop;
  return jsonb_array_length(p_actions);
end $$;

