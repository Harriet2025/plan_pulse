/** The user's partners (with unread messages, last message and chat streak), invites received, and invites waiting. */
create function public.partners_payload() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_me uuid := auth.uid();
  p public.partnerships;
  v_partner uuid;
  v_out boolean;
  v_read bigint;
  v_last public.partner_messages;
  v_partners jsonb := '[]'::jsonb;
  v_incoming jsonb := '[]'::jsonb;
  v_outgoing jsonb := '[]'::jsonb;
begin
  for p in select * from private.user_partnerships(v_me) loop
    v_out := p.inviter_id = v_me;
    if p.status = 'PENDING' then
      if v_out then
        v_outgoing := v_outgoing || jsonb_build_object('id', p.id, 'email', p.invitee_email, 'sent_at', p.created_at);
      else
        v_incoming := v_incoming || jsonb_build_object('id', p.id, 'sent_at', p.created_at, 'from',
          private.partner_profile(p.inviter_id) || jsonb_build_object('email', (select lower(email) from auth.users where id = p.inviter_id)));
      end if;
      continue;
    end if;
    v_partner := case when v_out then p.invitee_id else p.inviter_id end;
    v_read := case when v_out then p.inviter_read_id else p.invitee_read_id end;
    v_last := null;
    select * into v_last from public.partner_messages where partnership_id = p.id order by id desc limit 1;
    v_partners := v_partners || jsonb_build_object(
      'id', p.id, 'partner', private.partner_profile(v_partner), 'since', p.accepted_at,
      'unread', (select count(*) from public.partner_messages where partnership_id = p.id and sender_id <> v_me and id > v_read),
      'last', case when v_last.id is not null then jsonb_build_object('id', v_last.id, 'mine', v_last.sender_id = v_me, 'kind', v_last.kind,
        'body', case when char_length(v_last.body) > 80 then left(v_last.body, 79) || '…' else v_last.body end, 'at', v_last.created_at) end,
      'chat_streak', private.chat_streak(p.id, v_me),
      'my_shares', private.shares_of(p.id, v_me), 'their_shares', private.shares_of(p.id, v_partner));
  end loop;
  return jsonb_build_object('partners', v_partners, 'incoming', v_incoming, 'outgoing', v_outgoing);
end $$;

/** Invites an email address. Returns the lists, plus invite_id (a new invite to email) or a message (theirs was accepted). */
create function public.invite_partner(p_email text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_me uuid := auth.uid();
  v_mine text := private.my_email();
  v_email text := lower(btrim(p_email));
  v_theirs bigint;
  v_id bigint;
begin
  if v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' or char_length(v_email) > 255 then raise exception 'Enter a valid email address.'; end if;
  if v_email = v_mine then raise exception 'That is your own email. Invite someone else.'; end if;
  -- At most 20 invites a day, so the invite box cannot be used to spam
  if (select count(*) from public.partnerships where inviter_id = v_me and created_at > now() - interval '1 day') >= 20 then
    raise exception 'You have sent a lot of invites today. Try again tomorrow.';
  end if;
  if private.accepted_count(v_me) + (select count(*) from public.partnerships where inviter_id = v_me and status = 'PENDING') >= 5 then
    raise exception 'You can have up to 5 partners, counting invites still waiting. Cancel one first.';
  end if;
  -- If that person already invited you, inviting them back simply accepts their invite
  select p.id into v_theirs from public.partnerships p join auth.users u on u.id = p.inviter_id
  where lower(u.email) = v_email and p.status = 'PENDING' and p.invitee_id is null and p.invitee_email = v_mine;
  if v_theirs is not null then
    update public.partnerships set status = 'ACCEPTED', invitee_id = v_me, accepted_at = now() where id = v_theirs;
    return public.partners_payload() || jsonb_build_object('message', 'They had already invited you, so you are now partners.');
  end if;
  -- Already partners, or already invited
  if exists (select 1 from public.partnerships p left join auth.users u on u.id = p.inviter_id
             where (p.inviter_id = v_me and p.invitee_email = v_email) or (p.status = 'ACCEPTED' and p.invitee_id = v_me and lower(u.email) = v_email)) then
    raise exception 'You have already invited this person, or you are partners already.';
  end if;
  insert into public.partnerships (inviter_id, invitee_email) values (v_me, v_email) returning id into v_id;
  return public.partners_payload() || jsonb_build_object('invite_id', v_id);
end $$;

create function public.accept_partner(p_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_me uuid := auth.uid();
  p public.partnerships;
begin
  select * into p from public.partnerships where id = p_id and status = 'PENDING' and inviter_id <> v_me and invitee_id is null and invitee_email = private.my_email();
  if not found then raise exception 'Only an invite sent to you can be accepted.'; end if;
  if private.accepted_count(v_me) >= 5 or private.accepted_count(p.inviter_id) >= 5 then raise exception 'One of you already has 5 partners.'; end if;
  if exists (select 1 from public.partnerships where status = 'ACCEPTED' and ((inviter_id = v_me and invitee_id = p.inviter_id) or (inviter_id = p.inviter_id and invitee_id = v_me))) then
    raise exception 'You are already partners.';
  end if;
  update public.partnerships set status = 'ACCEPTED', invitee_id = v_me, accepted_at = now() where id = p_id;
  return public.partners_payload() || jsonb_build_object('message', 'You are partners now. Choose what they can see of yours.', 'accepted', p_id);
end $$;

/** Declines an invite, cancels one you sent, or stops being partners (the chat goes for both). */
create function public.drop_partner(p_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
begin
  if not exists (select 1 from private.user_partnerships(auth.uid()) where id = p_id) then raise exception 'Invite or partner not found.'; end if;
  delete from public.partnerships where id = p_id;
  return public.partners_payload();
end $$;

/** What this partner may see of yours: categories, and optionally your day plans. */
create function public.set_partner_shares(p_id bigint, p_categories bigint[], p_day_plans boolean) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_me uuid := auth.uid();
  p public.partnerships := private.accepted_partnership(p_id);
  v_ids bigint[] := array(select distinct c from unnest(coalesce(p_categories, '{}')) as c);
begin
  if (select count(*) from public.categories where id = any (v_ids) and (user_id is null or user_id = v_me)) <> coalesce(array_length(v_ids, 1), 0) then
    raise exception 'Unknown category.';
  end if;
  delete from public.partner_shares where partnership_id = p.id and owner_id = v_me;
  insert into public.partner_shares (partnership_id, owner_id, category_id) select p.id, v_me, c from unnest(v_ids) as c;
  if p_day_plans then
    insert into public.partner_shares (partnership_id, owner_id, category_id) values (p.id, v_me, 0);
  end if;
  return public.partners_payload() || jsonb_build_object('message', 'Saved what they can see.');
end $$;

/**
 * What a partner shares: their goals (active ones, and ones finished in the last two weeks) with plans, their plans for
 * today on their own clock, and this week's scoreboard. Only what they chose to share, and nothing marked private.
 */
create function public.partner_view(p_id bigint) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_me uuid := auth.uid();
  p public.partnerships := private.accepted_partnership(p_id);
  v_partner uuid := case when p.inviter_id = v_me then p.invitee_id else p.inviter_id end;
  v_shares jsonb := private.shares_of(p.id, v_partner);
  v_today date := private.today_in((select timezone from public.profiles where id = v_partner));
begin
  return jsonb_build_object(
    'partner', private.partner_profile(v_partner), 'shares', v_shares, 'date', v_today,
    'goals', (select coalesce(jsonb_agg(jsonb_build_object(
        'id', g.id, 'title', g.title, 'category_id', g.category_id, 'priority', g.priority,
        'category', case when c.id is not null then jsonb_build_object('name', c.name, 'color', c.color_code) end,
        'timeframe', g.timeframe, 'due_date', g.due_date, 'status', g.status, 'completed_at', g.completed_at,
        'plans', (select coalesce(jsonb_agg(jsonb_build_object('text', s.task_description, 'done', s.is_completed) order by s.id), '[]'::jsonb) from public.sub_plans s where s.goal_id = g.id)
      ) order by g.created_at desc, g.id desc), '[]'::jsonb)
      from public.goals g left join public.categories c on c.id = g.category_id
      where g.user_id = v_partner and not g.is_private and v_shares @> to_jsonb(coalesce(g.category_id, 9))
        and g.status <> 'ARCHIVED' and (g.status <> 'COMPLETED' or g.completed_at >= now() - interval '14 days')),
    'today', (select coalesce(jsonb_agg(jsonb_build_object('title', d.title, 'start', to_char(d.start_time, 'HH24:MI'), 'minutes', d.duration_min, 'repeat', d.repeat_rule, 'done', m.state = 'DONE')
        order by d.start_time nulls last, d.id), '[]'::jsonb)
      from public.day_plans d left join public.day_plan_marks m on m.day_plan_id = d.id and m.on_date = v_today
      where d.user_id = v_partner and v_shares @> '0'::jsonb and not d.is_private and m.state is distinct from 'SKIPPED'
        and private.day_plan_occurs(d.plan_date, d.repeat_rule, d.repeat_days, d.repeat_until, v_today)),
    'scoreboard', jsonb_build_object('me', private.plans_done_this_week(v_me), 'them', private.plans_done_this_week(v_partner)));
end $$;

/** The chat with a partner, oldest first. Marks it read. */
create function public.get_messages(p_id bigint, p_after bigint default 0) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  p public.partnerships := private.accepted_partnership(p_id);
  v_rows jsonb := private.message_rows(p.id, greatest(p_after, 0));
begin
  perform private.mark_read(p, v_rows);
  return jsonb_build_object('messages', v_rows, 'chat_streak', private.chat_streak(p.id, auth.uid()));
end $$;

/**
 * Sends to a partner. p_action: text { body } | cheer { emoji, goal_id } | nudge | media { path, mime, w, h, caption },
 * where a media file is first uploaded to the chat-media bucket under "<partnership id>/".
 * Returns the new messages after p_after, the chat streak and message_id (for the push to the partner).
 */
create function public.send_message(p_id bigint, p_action text, p_fields jsonb default '{}', p_after bigint default 0) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_me uuid := auth.uid();
  p public.partnerships := private.accepted_partnership(p_id);
  v_partner uuid := case when p.inviter_id = v_me then p.invitee_id else p.inviter_id end;
  v_body text;
  v_goal public.goals;
  v_path text;
  v_mime text;
  v_msg bigint;
  v_rows jsonb;
begin
  if (select count(*) from public.partner_messages where sender_id = v_me and created_at > now() - interval '1 minute') >= 30 then
    raise exception 'Slow down a little, then try again.';
  end if;
  if p_action = 'text' then
    v_body := btrim(p_fields->>'body');
    if coalesce(char_length(v_body), 0) not between 1 and 1000 then raise exception 'A message is 1 to 1000 characters.'; end if;
    insert into public.partner_messages (partnership_id, sender_id, kind, body) values (p.id, v_me, 'TEXT', v_body) returning id into v_msg;
  elsif p_action = 'cheer' then
    v_body := p_fields->>'emoji';
    if v_body is null or not (v_body = any (array['🔥', '👏', '💪', '❤️', '🎉', '⭐'])) then raise exception 'Pick one of the cheers.'; end if;
    select * into v_goal from public.goals where id = (p_fields->>'goal_id')::bigint and user_id = v_partner;
    if not found or v_goal.is_private or not (private.shares_of(p.id, v_partner) @> to_jsonb(coalesce(v_goal.category_id, 9))) then
      raise exception 'That goal is not shared with you.';
    end if;
    insert into public.partner_messages (partnership_id, sender_id, kind, body, ref_goal_id) values (p.id, v_me, 'CHEER', v_body, v_goal.id) returning id into v_msg;
  elsif p_action = 'media' then
    v_body := coalesce(btrim(p_fields->>'caption'), '');
    v_path := p_fields->>'path';
    v_mime := p_fields->>'mime';
    if char_length(v_body) > 1000 then raise exception 'A caption is 1000 characters or fewer.'; end if;
    if v_mime is null or v_mime not in ('image/jpeg', 'image/gif', 'video/mp4', 'video/webm', 'video/quicktime') then raise exception 'Send a photo or a video.'; end if;
    -- At most 40 photos and videos a day from one person
    if (select count(*) from public.partner_messages where sender_id = v_me and kind in ('IMAGE', 'VIDEO') and created_at > now() - interval '1 day') >= 40 then
      raise exception 'That is a lot of photos and videos today. Try again tomorrow.';
    end if;
    if v_path is null or split_part(v_path, '/', 1) <> p.id::text
       or not exists (select 1 from storage.objects o where o.bucket_id = 'chat-media' and o.name = v_path and o.owner_id = v_me::text) then
      raise exception 'That file was not uploaded.';
    end if;
    insert into public.partner_messages (partnership_id, sender_id, kind, body, media_file, media_mime, media_w, media_h)
    values (p.id, v_me, case when v_mime like 'video/%' then 'VIDEO' else 'IMAGE' end, v_body, v_path, v_mime, (p_fields->>'w')::integer, (p_fields->>'h')::integer)
    returning id into v_msg;
  elsif p_action = 'nudge' then
    if exists (select 1 from public.partner_messages where partnership_id = p.id and sender_id = v_me and kind = 'NUDGE' and created_at > now() - interval '4 hours') then
      raise exception 'You nudged them already. You can nudge again in a few hours.';
    end if;
    insert into public.partner_messages (partnership_id, sender_id, kind, body) values (p.id, v_me, 'NUDGE', 'Nudge! Time to plan your day and get going.') returning id into v_msg;
  else
    raise exception 'Unknown action. Use text, cheer, media or nudge.';
  end if;
  v_rows := private.message_rows(p.id, greatest(p_after, 0));
  perform private.mark_read(p, v_rows);
  return jsonb_build_object('messages', v_rows, 'chat_streak', private.chat_streak(p.id, v_me), 'message_id', v_msg);
end $$;

/** Saves this device for notifications. A device that changes hands now belongs to whoever is signed in. */
create function public.subscribe_push(p_endpoint text, p_p256dh text, p_auth text, p_user_agent text default null) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if p_endpoint !~ '^https://' or char_length(p_endpoint) > 2000 or char_length(p_p256dh) > 255 or char_length(p_auth) > 64 then
    raise exception 'That device could not be saved.';
  end if;
  insert into public.push_subscriptions (user_id, endpoint, p256dh, auth, user_agent)
  values (auth.uid(), p_endpoint, p_p256dh, p_auth, left(p_user_agent, 255))
  on conflict (endpoint) do update set user_id = excluded.user_id, p256dh = excluded.p256dh, auth = excluded.auth, user_agent = excluded.user_agent;
end $$;

-- ---- Who may open which file (used by the storage rules below) ----

create function public.can_access_chat_path(p_path text) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.partnerships p
    where p.id::text = split_part(p_path, '/', 1) and p.status = 'ACCEPTED' and auth.uid() in (p.inviter_id, p.invitee_id))
$$;

create function public.can_see_avatar(p_path text) returns boolean
language sql stable security definer set search_path = '' as $$
  select split_part(p_path, '/', 1) = auth.uid()::text
    or exists (select 1 from public.partnerships p where p.status = 'ACCEPTED' and (
      (p.inviter_id = auth.uid() and p.invitee_id::text = split_part(p_path, '/', 1)) or
      (p.invitee_id = auth.uid() and p.inviter_id::text = split_part(p_path, '/', 1))))
$$;

