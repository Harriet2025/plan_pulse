  ('avatars', 'avatars', false, 5242880, array['image/jpeg']),
  ('chat-media', 'chat-media', false, 52428800, array['image/jpeg', 'image/gif', 'video/mp4', 'video/webm', 'video/quicktime']);

create policy "avatar: view" on storage.objects for select to authenticated
  using (bucket_id = 'avatars' and public.can_see_avatar(name));
create policy "avatar: add own" on storage.objects for insert to authenticated
  with check (bucket_id = 'avatars' and split_part(name, '/', 1) = (select auth.uid())::text);
