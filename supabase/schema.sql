/** The signed-in user's own confirmed email, in lower case. */
create function private.my_email() returns text
language sql stable security definer set search_path = '' as $$
  select lower(email) from auth.users where id = auth.uid() and email_confirmed_at is not null
$$;

/** Today on someone's own clock. An empty or unknown time zone counts as UTC. */
create function private.today_in(p_tz text) returns date
language plpgsql stable set search_path = '' as $$
begin
  return (now() at time zone p_tz)::date;
exception when others then
  return (now() at time zone 'UTC')::date;
end $$;

create function private.is_rest_day(p_mask integer, p_day date) returns boolean
language sql immutable set search_path = '' as $$
  select ((p_mask >> (extract(isodow from p_day)::integer - 1)) & 1) = 1
$$;

/** Work days (not rest days) strictly between the last active day and today that had no activity. */
create function private.missed_workdays(p_last date, p_mask integer, p_today date) returns integer
language sql immutable set search_path = '' as $$
  select case
    when p_last is null then 0
    when p_today - p_last - 1 > 31 then 1000   -- a longer gap than this can never be covered by freezes
    else (select count(*)::integer from generate_series(p_last + 1, p_today - 1, interval '1 day') as d
          where not private.is_rest_day(p_mask, d::date))
  end
$$;

/** Everything the app knows about the signed-in user. A streak that can no longer be saved shows as 0. */
create function private.user_payload(p_id uuid) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  u public.profiles;
  v_email text;
  v_today date;
  v_missed integer;
  v_alive boolean;
  v_count integer;
begin
  select * into u from public.profiles where id = p_id;
  if not found then return null; end if;
  select email into v_email from auth.users where id = p_id;
  v_today := private.today_in(u.timezone);
  v_missed := private.missed_workdays(u.last_active_date, u.rest_days, v_today);
  v_alive := u.streak_count > 0 and v_missed <= u.streak_freezes;
  v_count := case when v_alive then u.streak_count else 0 end;
  return jsonb_build_object(
    'id', u.id, 'email', v_email, 'display_name', u.display_name,
    'avatar_v', extract(epoch from u.avatar_updated_at)::bigint,
    'streak_count', v_count, 'best_streak', greatest(u.best_streak, v_count), 'streak_freezes', u.streak_freezes,
    'rest_days', (select coalesce(jsonb_agg(d order by d), '[]'::jsonb) from generate_series(1, 7) as d where ((u.rest_days::integer >> (d - 1)) & 1) = 1),
    'last_active', u.last_active_date, 'streak_active_today', u.last_active_date = v_today,
    'streak_protected', v_alive and v_missed > 0, 'rest_today', private.is_rest_day(u.rest_days, v_today),
    'daily_capacity_min', u.daily_capacity_min, 'digest_enabled', u.digest_enabled, 'digest_time', u.digest_time, 'timezone', u.timezone
  );
end $$;

/** What partners may know about a user: name, photo version and streak. */
create function private.partner_profile(p_id uuid) returns jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_build_object('id', p->'id', 'display_name', p->'display_name', 'avatar_v', p->'avatar_v',
    'streak_count', p->'streak_count', 'best_streak', p->'best_streak', 'streak_active_today', p->'streak_active_today')
  from private.user_payload(p_id) as p
