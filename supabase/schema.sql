/** Every new account gets a profile, named from the sign-up form. */
create function private.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(nullif(left(btrim(new.raw_user_meta_data ->> 'display_name'), 100), ''), left(split_part(new.email, '@', 1), 100), 'Friend'));
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users for each row execute function private.handle_new_user();

create function private.touch_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end $$;

/** Names must not clash, ignoring case, with a built-in category or another of the user's. At most 20 of your own. */
create function private.check_category() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  new.name := regexp_replace(btrim(new.name), '\s+', ' ', 'g');
  new.color_code := upper(new.color_code);
  if char_length(new.name) not between 1 and 40 then raise exception 'A category name is 1 to 40 characters.'; end if;
  if tg_op = 'INSERT' and (select count(*) from public.categories where user_id = new.user_id) >= 20 then
    raise exception 'You can have up to 20 categories of your own.';
  end if;
  if exists (select 1 from public.categories where lower(name) = lower(new.name) and (user_id is null or user_id = new.user_id) and id <> coalesce(new.id, 0)) then
    raise exception 'You already have a category called "%".', new.name;
  end if;
  return new;
end $$;
create trigger categories_check before insert or update on public.categories for each row
  when (new.user_id is not null) execute function private.check_category();

/** A goal without a due date ends with its current period, on the user's clock. Restoring a finished goal finishes it again. */
create function private.goal_defaults() returns trigger
language plpgsql security definer set search_path = '' as $$
declare v_today date;
begin
  new.title := btrim(new.title);
  if new.due_date is null and tg_op = 'INSERT' then
    v_today := private.today_in((select timezone from public.profiles where id = new.user_id));
    new.due_date := case new.timeframe
      when 'WEEKLY' then v_today + (7 - extract(isodow from v_today)::integer)
      when 'MONTHLY' then (date_trunc('month', v_today) + interval '1 month - 1 day')::date
      else make_date(extract(year from v_today)::integer, 12, 31) end;
  end if;
  if tg_op = 'UPDATE' and old.status = 'ARCHIVED' and new.status = 'ACTIVE' then
    if ((private.goal_progress(new.id))->>'percentage')::integer = 100 then
      new.status := 'COMPLETED';
      new.completed_at := now();
    end if;
  end if;
  return new;
end $$;
create trigger goals_defaults before insert or update on public.goals for each row execute function private.goal_defaults();
create trigger goals_updated before update on public.goals for each row execute function private.touch_updated_at();

/** completed_at feeds the partners' scoreboard; re-ticking a done plan keeps its first time. */
create function private.sub_plan_stamp() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.task_description := btrim(new.task_description);
  new.completed_at := case when new.is_completed then coalesce(new.completed_at, now()) end;
  return new;
end $$;
create trigger sub_plans_stamp before insert or update on public.sub_plans for each row execute function private.sub_plan_stamp();

/** A goal moves to COMPLETED at 100% and back to ACTIVE if a plan is unticked or added. Archived goals are left alone. */
create function private.sub_plan_sync_goal() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_goal bigint := coalesce(new.goal_id, old.goal_id);
  v_pct jsonb := private.goal_progress(v_goal);
begin
  if (v_pct->>'total')::integer > 0 and (v_pct->>'percentage')::integer = 100 then
    update public.goals set status = 'COMPLETED', completed_at = now() where id = v_goal and status = 'ACTIVE';
  elsif (v_pct->>'percentage')::integer < 100 then
    update public.goals set status = 'ACTIVE', completed_at = null where id = v_goal and status = 'COMPLETED';
  end if;
  return null;
end $$;
create trigger sub_plans_sync after insert or delete or update of is_completed on public.sub_plans for each row execute function private.sub_plan_sync_goal();

/** Keeps a day plan's repeat fields consistent, and its time within the day. */
create function private.day_plan_check() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  new.title := btrim(new.title);
  if tg_op = 'INSERT' and (select count(*) from public.day_plans where user_id = new.user_id) >= 5000 then
    raise exception 'You have reached the limit of 5000 day plans. Delete some old ones first.';
  end if;
  if new.repeat_rule = 'WEEKLY' and new.repeat_days = 0 then   -- no weekdays chosen: the weekday of the first day
    new.repeat_days := 1 << (extract(isodow from new.plan_date)::integer - 1);
  end if;
  if new.repeat_rule <> 'WEEKLY' then new.repeat_days := 0; end if;
  if new.repeat_rule = 'NONE' then
    new.repeat_until := null;
  elsif new.repeat_until is not null and new.repeat_until < new.plan_date then
    raise exception 'A repeating plan cannot end before it starts.';
  end if;
  if new.start_time is not null and new.duration_min is not null
     and extract(hour from new.start_time) * 60 + extract(minute from new.start_time) + new.duration_min > 1440 then
    raise exception 'A plan has to end by midnight. Split it into two days.';
  end if;
  return new;
end $$;
create trigger day_plans_check before insert or update on public.day_plans for each row execute function private.day_plan_check();

/** A one-off plan that moved to another day takes its done mark with it. */
create function private.day_plan_moved() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if new.repeat_rule = 'NONE' and new.plan_date <> old.plan_date then
    delete from public.day_plan_marks where day_plan_id = new.id and on_date <> old.plan_date;
    update public.day_plan_marks set on_date = new.plan_date where day_plan_id = new.id;
  end if;
  return null;
end $$;
create trigger day_plans_moved after update of plan_date on public.day_plans for each row execute function private.day_plan_moved();

