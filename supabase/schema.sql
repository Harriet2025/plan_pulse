-- AuraGoal on Supabase: tables, access rules (RLS), the rules the PHP backend used to enforce, and file storage.
-- Run once, on a new project, in the Supabase SQL Editor. It stops with an error if the tables already exist, and it
-- deletes nothing.
--
-- The browser talks to the database directly, so nothing here may trust the browser:
--   * every table has row level security, and each role gets only the columns it needs;
--   * streaks and badges can only change through functions that work them out from the database;
--   * partners never read each other's tables: partner_view() and friends return only what was shared.
-- Passwords and reset links are handled by Supabase Auth, so users.password_hash and password_resets are gone.

create schema private;   -- helpers only: not reachable through the API
revoke all on schema private from public;

