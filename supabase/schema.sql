/** The user finished something today: counts the day and saves the streak. Events: freeze_used, freeze_earned, reset. */
create function private.touch_streak(p_id uuid) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  u public.profiles;
  v_today date;
  v_missed integer;
  v_streak integer;
  v_best integer;
  v_freezes integer;
  v_events jsonb := '[]'::jsonb;
begin
  select * into u from public.profiles where id = p_id for update;
  v_today := private.today_in(u.timezone);
  v_streak := u.streak_count; v_best := u.best_streak; v_freezes := u.streak_freezes;
  if u.last_active_date = v_today then
    return jsonb_build_object('count', v_streak, 'best', v_best, 'freezes', v_freezes, 'events', v_events);
  end if;

  v_missed := private.missed_workdays(u.last_active_date, u.rest_days, v_today);
  if v_streak > 0 and v_missed <= v_freezes then
    if v_missed > 0 then
      v_freezes := v_freezes - v_missed;
      v_events := v_events || jsonb_build_object('type', 'freeze_used', 'count', v_missed, 'streak', v_streak);
    end if;
    v_streak := v_streak + 1;
  else
    if v_streak >= 2 then
      v_events := v_events || jsonb_build_object('type', 'reset', 'previous', v_streak, 'best', greatest(v_best, v_streak));
    end if;
    v_streak := 1;
  end if;
  if v_streak % 7 = 0 and v_freezes < 2 then
    v_freezes := v_freezes + 1;
    v_events := v_events || jsonb_build_object('type', 'freeze_earned', 'streak', v_streak);
  end if;
  v_best := greatest(v_best, v_streak);
  update public.profiles set streak_count = v_streak, best_streak = v_best, streak_freezes = v_freezes, last_active_date = v_today where id = p_id;
  return jsonb_build_object('count', v_streak, 'best', v_best, 'freezes', v_freezes, 'events', v_events);
end $$;

create function private.goal_progress(p_goal bigint) returns jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'percentage', case when count(*) > 0 then round(100.0 * count(*) filter (where is_completed) / count(*))::integer else 0 end,
    'completed', count(*) filter (where is_completed), 'total', count(*))
  from public.sub_plans where goal_id = p_goal
$$;

/** Whether a day plan happens on a day. Mirrors occursOn() in src/lib/utils.js, so keep the two in step. */
create function private.day_plan_occurs(p_first date, p_rule text, p_days integer, p_until date, p_day date) returns boolean
language sql immutable set search_path = '' as $$
  select p_day >= p_first and (p_until is null or p_day <= p_until) and case p_rule
    when 'NONE' then p_day = p_first
    when 'DAILY' then true
    when 'WEEKLY' then ((p_days >> (extract(isodow from p_day)::integer - 1)) & 1) = 1
    when 'MONTHLY' then extract(day from p_day) = least(extract(day from p_first),
      extract(day from (date_trunc('month', p_day) + interval '1 month - 1 day')))
    else false end
$$;

