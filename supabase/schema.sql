create table public.profiles (
  id                 uuid primary key references auth.users (id) on delete cascade,
  display_name       text not null check (char_length(btrim(display_name)) between 1 and 100),
  streak_count       integer not null default 0,
  best_streak        integer not null default 0,        -- longest streak ever, kept across resets
  streak_freezes     smallint not null default 0,       -- each covers one missed day; earned every 7 days, max 2
  rest_days          smallint not null default 0        -- weekdays that never break the streak: bit 0 = Monday ... bit 6 = Sunday
                     check (rest_days between 0 and 127 and length(replace((rest_days::integer)::bit(7)::text, '0', '')) <= 3),
  daily_capacity_min smallint not null default 240 check (daily_capacity_min between 30 and 960),
  digest_enabled     boolean not null default false,    -- morning email of the day's plan
  digest_time        text not null default '07:30' check (digest_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  timezone           text not null default '',          -- from the user's browser, e.g. 'Africa/Accra'; empty = UTC
  last_active_date   date,                              -- drives streak_count
  avatar_updated_at  timestamptz,                       -- null = no profile photo
  created_at         timestamptz not null default now()
);

