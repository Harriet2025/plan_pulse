/** Days in a row (UTC) both partners sent something; still alive when the last such day was yesterday. */
create function private.chat_streak(p_partnership bigint, p_me uuid) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_both date[];
  v_today date := (now() at time zone 'UTC')::date;
  v_day date;
  v_count integer := 0;
  v_best integer := 0;
  v_run integer := 0;
  v_prev date;
  d date;
begin
  select coalesce(array_agg(x.day order by x.day), '{}') into v_both from (
    select (created_at at time zone 'UTC')::date as day from public.partner_messages
    where partnership_id = p_partnership and kind in ('TEXT', 'CHEER', 'IMAGE', 'VIDEO') and created_at >= now() - interval '400 days'
    group by 1 having count(distinct sender_id) >= 2
  ) as x;
  v_day := case when v_today = any (v_both) then v_today else v_today - 1 end;
  while v_day = any (v_both) loop
    v_count := v_count + 1;
    v_day := v_day - 1;
  end loop;
  foreach d in array v_both loop
    v_run := case when v_prev is not null and v_prev + 1 = d then v_run + 1 else 1 end;
    v_best := greatest(v_best, v_run);
    v_prev := d;
  end loop;
  return jsonb_build_object('count', v_count, 'best', v_best,
    'me_today', exists (select 1 from public.partner_messages where partnership_id = p_partnership and sender_id = p_me and kind in ('TEXT', 'CHEER', 'IMAGE', 'VIDEO') and (created_at at time zone 'UTC')::date = v_today),
    'them_today', exists (select 1 from public.partner_messages where partnership_id = p_partnership and sender_id <> p_me and kind in ('TEXT', 'CHEER', 'IMAGE', 'VIDEO') and (created_at at time zone 'UTC')::date = v_today));
end $$;

/** Plans finished this week (Monday to Sunday, UTC): a goal's plans ticked, plus days of day plans done. */
create function private.plans_done_this_week(p_id uuid) returns integer
language sql stable security definer set search_path = '' as $$
  with w as (select date_trunc('week', now() at time zone 'UTC')::date as monday)
  select (select count(*) from public.sub_plans s join public.goals g on g.id = s.goal_id, w
          where g.user_id = p_id and s.is_completed and (s.completed_at at time zone 'UTC')::date between w.monday and w.monday + 6)::integer
       + (select count(*) from public.day_plan_marks m join public.day_plans dp on dp.id = m.day_plan_id, w
          where dp.user_id = p_id and m.state = 'DONE' and m.on_date between w.monday and w.monday + 6)::integer
$$;

/** The chat, oldest first: the latest 200, or only those after p_after. A photo or video carries its storage path. */
create function private.message_rows(p_partnership bigint, p_after bigint) returns jsonb
language sql stable security definer set search_path = '' as $$
  select coalesce(jsonb_agg(row order by (row->>'id')::bigint), '[]'::jsonb) from (
    select jsonb_build_object('id', m.id, 'sender_id', m.sender_id, 'kind', m.kind, 'body', m.body, 'goal_id', m.ref_goal_id, 'goal_title', g.title,
      'at', m.created_at,
      'media', case when m.media_mime is not null then jsonb_build_object('path', m.media_file, 'mime', m.media_mime, 'w', m.media_w, 'h', m.media_h) end) as row
    from public.partner_messages m left join public.goals g on g.id = m.ref_goal_id
    where m.partnership_id = p_partnership and m.id > p_after
    order by m.id desc limit 200
  ) as x
$$;

create function private.mark_read(p public.partnerships, p_rows jsonb) returns void
language plpgsql security definer set search_path = '' as $$
declare v_last bigint := (p_rows -> -1 ->> 'id')::bigint;
begin
  if v_last is null then return; end if;
  if p.inviter_id = auth.uid() then
    update public.partnerships set inviter_read_id = greatest(inviter_read_id, v_last) where id = p.id;
  else
    update public.partnerships set invitee_read_id = greatest(invitee_read_id, v_last) where id = p.id;
  end if;
end $$;

