/**
 * Everything the two of you do together: shared goals (active first, then finished; archived ones last), this week's
 * challenge, the last 12 weeks' challenges, how many you have won and how many weeks in a row.
 */
create function public.together_view(p_id bigint) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_me uuid := auth.uid();
  p public.partnerships := private.accepted_partnership(p_id);
  v_them uuid := private.partner_of(p);
  v_monday date := private.this_monday();
  c public.partner_challenges;
  v_now jsonb;
  v_res jsonb;
  v_history jsonb := '[]'::jsonb;
  v_wins integer := 0;
  v_streak integer := 0;
  v_expect date := v_monday - 7;
  v_run boolean := true;
begin
  select * into c from public.partner_challenges where partnership_id = p.id and week_start = v_monday;
  if found then v_now := private.challenge_json(c, v_me, v_them); end if;
  for c in select * from public.partner_challenges where partnership_id = p.id and week_start < v_monday order by week_start desc loop
    v_res := private.challenge_json(c, v_me, v_them);
    if (v_res->>'won')::boolean then v_wins := v_wins + 1; end if;
    if v_run and c.week_start = v_expect and (v_res->>'won')::boolean then v_streak := v_streak + 1; v_expect := v_expect - 7; else v_run := false; end if;
    if jsonb_array_length(v_history) < 12 then
      v_history := v_history || jsonb_build_object('week_start', c.week_start, 'text', v_res->'text', 'won', v_res->'won', 'me', v_res->'me', 'them', v_res->'them', 'target', c.target);
    end if;
  end loop;
  if (v_now->>'won')::boolean then v_wins := v_wins + 1; v_streak := v_streak + 1; end if;
  return jsonb_build_object(
    'week_start', v_monday, 'today', (now() at time zone 'UTC')::date,
    'goals', (select coalesce(jsonb_agg(private.team_goal_json(g, v_me)
               order by case g.status when 'ACTIVE' then 0 when 'COMPLETED' then 1 else 2 end, g.due_date, g.id), '[]'::jsonb)
              from public.team_goals g where g.partnership_id = p.id),
    'challenge', v_now, 'history', v_history, 'wins', v_wins, 'win_streak', v_streak);
end $$;

/**
 * Starts a shared goal (p_goal null) or changes one. p_fields: { title, emoji, why, timeframe, due_date }.
 * p_plans: the full list, in order: [{ id?, text, who: TOGETHER | EACH | ME | THEM }]. Plans left out are deleted; a plan
 * whose "who" changes starts again unticked. Either partner may change a shared goal.
 */
create function public.save_team_goal(p_id bigint, p_goal bigint, p_fields jsonb, p_plans jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_me uuid := auth.uid();
  p public.partnerships := private.accepted_partnership(p_id);
  v_them uuid := private.partner_of(p);
  v_title text := btrim(p_fields->>'title');
  v_emoji text := coalesce(nullif(btrim(p_fields->>'emoji'), ''), '🎯');
  v_why text := nullif(btrim(p_fields->>'why'), '');
  v_tf text := coalesce(p_fields->>'timeframe', 'MONTHLY');
  v_due date := (p_fields->>'due_date')::date;
  v_goal public.team_goals;
  v_keep bigint[] := '{}';
  x jsonb;
  v_pos integer := 0;
  v_text text;
  v_who text;
  v_assignee uuid;
  v_plan public.team_plans;
  v_new bigint;
  v_msg bigint;
begin
  if coalesce(char_length(v_title), 0) not between 1 and 255 then raise exception 'Give the goal a name of 1 to 255 characters.'; end if;
  if char_length(v_emoji) > 8 then raise exception 'Pick one emoji.'; end if;
  if char_length(v_why) > 500 then raise exception 'Keep the "why" to 500 characters.'; end if;
  if v_tf not in ('WEEKLY', 'MONTHLY', 'YEARLY') then raise exception 'A shared goal is for a week, a month or a year.'; end if;
  if v_due is null or v_due not between '2000-01-01' and '2100-12-31' then raise exception 'Pick when the goal ends.'; end if;
  if jsonb_typeof(p_plans) <> 'array' or jsonb_array_length(p_plans) > 50 then raise exception 'A shared goal can have up to 50 plans.'; end if;

  if p_goal is null then
    if (select count(*) from public.team_goals where partnership_id = p.id and status = 'ACTIVE') >= 30 then
      raise exception 'You have 30 shared goals going. Finish or archive one first.';
    end if;
    insert into public.team_goals (partnership_id, created_by, title, emoji, why, timeframe, due_date)
    values (p.id, v_me, v_title, v_emoji, v_why, v_tf, v_due) returning * into v_goal;
    v_msg := private.team_note(p.id, format('started a shared goal: %s %s', v_emoji, v_title));
  else
    select * into v_goal from public.team_goals where id = p_goal and partnership_id = p.id for update;
    if not found then raise exception 'Shared goal not found.'; end if;
    update public.team_goals set title = v_title, emoji = v_emoji, why = v_why, timeframe = v_tf, due_date = v_due where id = v_goal.id;
  end if;

  for x in select * from jsonb_array_elements(p_plans) loop
    v_text := btrim(x->>'text');
    if coalesce(char_length(v_text), 0) = 0 then continue; end if;
    if char_length(v_text) > 500 then raise exception 'A plan is up to 500 characters.'; end if;
    v_who := coalesce(x->>'who', 'TOGETHER');
    v_assignee := (case v_who when 'ME' then v_me when 'THEM' then v_them end);
    v_who := (case when v_who in ('ME', 'THEM') then 'ONE' when v_who in ('TOGETHER', 'EACH') then v_who end);
    if v_who is null then raise exception 'Each plan is for both of you together, each of you, you or your partner.'; end if;
    v_pos := v_pos + 1;
    v_plan := null;
    if x ? 'id' and x->>'id' is not null then
      select * into v_plan from public.team_plans where id = (x->>'id')::bigint and team_goal_id = v_goal.id;
    end if;
    if v_plan.id is not null then
      if v_plan.who <> v_who or v_plan.assignee is distinct from v_assignee then
        delete from public.team_plan_marks where team_plan_id = v_plan.id;
      end if;
      update public.team_plans set task = v_text, who = v_who, assignee = v_assignee, position = v_pos where id = v_plan.id;
      v_keep := v_keep || v_plan.id;
    else
      insert into public.team_plans (team_goal_id, task, who, assignee, position) values (v_goal.id, v_text, v_who, v_assignee, v_pos)
      returning id into v_new;
      v_keep := v_keep || v_new;
    end if;
  end loop;
  delete from public.team_plans where team_goal_id = v_goal.id and not (id = any (v_keep));
  if v_goal.status <> 'ARCHIVED' and private.team_goal_sync(v_goal.id) then
    v_msg := private.team_note(p.id, format('completed the shared goal: %s %s 🎉', v_emoji, v_title));
  end if;
  return public.together_view(p.id) || jsonb_build_object('goal_id', v_goal.id, 'message_id', v_msg);
end $$;

/** Ticks or unticks your part of a shared plan. Unticking a "together" plan unticks it for both. Finishing counts as an active day. */
create function public.mark_team_plan(p_plan bigint, p_done boolean) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_me uuid := auth.uid();
  t public.team_plans;
  g public.team_goals;
  p public.partnerships;
  v_finished boolean := false;
  v_msg bigint;
  v_streak jsonb;
begin
  select * into t from public.team_plans where id = p_plan;
  if found then select * into g from public.team_goals where id = t.team_goal_id for update; end if;
  if t.id is null or g.id is null then raise exception 'Plan not found.'; end if;
  p := private.accepted_partnership(g.partnership_id);
  if g.status = 'ARCHIVED' then raise exception 'Restore this shared goal first.'; end if;
  if t.who = 'ONE' and t.assignee <> v_me then raise exception 'That plan is your partner''s to tick.'; end if;
  if p_done then
    insert into public.team_plan_marks (team_plan_id, user_id) values (t.id, v_me) on conflict do nothing;
    v_streak := private.touch_streak(v_me);
  elsif t.who = 'TOGETHER' then
    delete from public.team_plan_marks where team_plan_id = t.id;
  else
    delete from public.team_plan_marks where team_plan_id = t.id and user_id = v_me;
  end if;
  v_finished := private.team_goal_sync(g.id);
  if v_finished then v_msg := private.team_note(p.id, format('completed the shared goal: %s %s 🎉', g.emoji, g.title)); end if;
  return public.together_view(p.id) || jsonb_build_object('finished', v_finished, 'message_id', v_msg, 'streak', v_streak);
end $$;

/** archive | restore | delete a shared goal. Either partner may; deleting says so in the chat. */
create function public.set_team_goal(p_goal bigint, p_action text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  g public.team_goals;
  p public.partnerships;
  v_msg bigint;
begin
  select * into g from public.team_goals where id = p_goal for update;
  if not found then raise exception 'Shared goal not found.'; end if;
  p := private.accepted_partnership(g.partnership_id);
  if p_action = 'archive' then
    update public.team_goals set status = 'ARCHIVED' where id = g.id;
  elsif p_action = 'restore' then
    update public.team_goals set status = 'ACTIVE', completed_at = null where id = g.id and status = 'ARCHIVED';
    perform private.team_goal_sync(g.id);
  elsif p_action = 'delete' then
    delete from public.team_goals where id = g.id;
    v_msg := private.team_note(p.id, format('deleted the shared goal %s %s', g.emoji, g.title));
  else
    raise exception 'A shared goal can be archived, restored or deleted.';
  end if;
  return public.together_view(p.id) || jsonb_build_object('message_id', v_msg);
end $$;

/**
 * Sets this week's challenge (replacing one already set). p_kind: EACH_PLANS | TOTAL_PLANS | CHAT_DAYS | HABIT, where
 * HABIT needs p_title. Says so in the chat.
 */
create function public.set_challenge(p_id bigint, p_kind text, p_target integer, p_title text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_me uuid := auth.uid();
  p public.partnerships := private.accepted_partnership(p_id);
  v_monday date := private.this_monday();
  v_title text := nullif(btrim(p_title), '');
  v_old public.partner_challenges;
  v_msg bigint;
  v_max integer := (case p_kind when 'EACH_PLANS' then 100 when 'TOTAL_PLANS' then 200 else 7 end);
begin
  if p_kind not in ('EACH_PLANS', 'TOTAL_PLANS', 'CHAT_DAYS', 'HABIT') then raise exception 'Pick a kind of challenge.'; end if;
  if p_target is null or p_target < 1 or p_target > v_max then raise exception 'That target does not fit this challenge.'; end if;
  if p_kind = 'HABIT' and coalesce(char_length(v_title), 0) not between 1 and 120 then raise exception 'Say what you will both do, in up to 120 characters.'; end if;
  if p_kind <> 'HABIT' then v_title := null; end if;
  if (select count(*) from public.partner_messages where partnership_id = p.id and sender_id = v_me and kind = 'TEAM' and created_at > now() - interval '1 minute') >= 10 then
    raise exception 'Slow down a little, then try again.';
  end if;
  select * into v_old from public.partner_challenges where partnership_id = p.id and week_start = v_monday for update;
  if found then
    if v_old.kind <> p_kind or v_old.title is distinct from v_title then delete from public.challenge_checkins where challenge_id = v_old.id; end if;
    update public.partner_challenges set kind = p_kind, target = p_target, title = v_title, set_by = v_me where id = v_old.id;
  else
    insert into public.partner_challenges (partnership_id, week_start, kind, target, title, set_by) values (p.id, v_monday, p_kind, p_target, v_title, v_me);
  end if;
  v_msg := private.team_note(p.id, format('%s this week''s challenge: %s', (case when v_old.id is null then 'set' else 'changed' end), private.challenge_text(p_kind, p_target, v_title)));
  return public.together_view(p.id) || jsonb_build_object('message_id', v_msg);
end $$;

create function public.clear_challenge(p_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  p public.partnerships := private.accepted_partnership(p_id);
  v_msg bigint;
begin
  delete from public.partner_challenges where partnership_id = p.id and week_start = private.this_monday();
  if found then v_msg := private.team_note(p.id, 'called off this week''s challenge'); end if;
  return public.together_view(p.id) || jsonb_build_object('message_id', v_msg);
end $$;

/** HABIT challenge: "I did it today" (or undo it). */
create function public.challenge_checkin(p_id bigint, p_done boolean) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  p public.partnerships := private.accepted_partnership(p_id);
  c public.partner_challenges;
  v_today date := (now() at time zone 'UTC')::date;
begin
  select * into c from public.partner_challenges where partnership_id = p.id and week_start = private.this_monday() and kind = 'HABIT';
  if not found then raise exception 'There is no habit challenge this week.'; end if;
  if p_done then
    insert into public.challenge_checkins (challenge_id, user_id, on_date) values (c.id, auth.uid(), v_today) on conflict do nothing;
  else
    delete from public.challenge_checkins where challenge_id = c.id and user_id = auth.uid() and on_date = v_today;
  end if;
  return public.together_view(p.id);
end $$;

