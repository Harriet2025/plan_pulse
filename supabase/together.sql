create function private.this_monday() returns date
language sql stable set search_path = '' as $$
  select date_trunc('week', now() at time zone 'UTC')::date
$$;

/** Plans someone finished in the week starting p_monday: their goals' plans, day plans, and shared plans they ticked. */
create function private.plans_done_in_week(p_id uuid, p_monday date) returns integer
language sql stable security definer set search_path = '' as $$
  select (select count(*) from public.sub_plans s join public.goals g on g.id = s.goal_id
          where g.user_id = p_id and s.is_completed and (s.completed_at at time zone 'UTC')::date between p_monday and p_monday + 6)::integer
       + (select count(*) from public.day_plan_marks m join public.day_plans dp on dp.id = m.day_plan_id
          where dp.user_id = p_id and m.state = 'DONE' and m.on_date between p_monday and p_monday + 6)::integer
       + (select count(*) from public.team_plan_marks t
          where t.user_id = p_id and (t.done_at at time zone 'UTC')::date between p_monday and p_monday + 6)::integer
$$;

create or replace function private.plans_done_this_week(p_id uuid) returns integer
language sql stable security definer set search_path = '' as $$
  select private.plans_done_in_week(p_id, private.this_monday())
$$;

/** TOGETHER: either partner ticked it. EACH: both did. ONE: the partner it is for did. */
create function private.team_plan_done(p_plan bigint, p_who text, p_assignee uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select case p_who
    when 'TOGETHER' then exists (select 1 from public.team_plan_marks where team_plan_id = p_plan)
    when 'EACH' then (select count(*) from public.team_plan_marks where team_plan_id = p_plan) >= 2
    else exists (select 1 from public.team_plan_marks where team_plan_id = p_plan and user_id = p_assignee) end
$$;

create function private.team_goal_json(g public.team_goals, p_me uuid) returns jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'id', g.id, 'title', g.title, 'emoji', g.emoji, 'why', g.why, 'timeframe', g.timeframe, 'due_date', g.due_date,
    'status', g.status, 'completed_at', g.completed_at, 'created_at', g.created_at, 'started_by_me', g.created_by = p_me,
    'plans', (select coalesce(jsonb_agg(jsonb_build_object(
        'id', t.id, 'text', t.task, 'who', case when t.who <> 'ONE' then t.who when t.assignee = p_me then 'ME' else 'THEM' end,
        'me_done', exists (select 1 from public.team_plan_marks m where m.team_plan_id = t.id and m.user_id = p_me),
        'them_done', exists (select 1 from public.team_plan_marks m where m.team_plan_id = t.id and m.user_id <> p_me),
        'done', private.team_plan_done(t.id, t.who, t.assignee)
      ) order by t.position, t.id), '[]'::jsonb) from public.team_plans t where t.team_goal_id = g.id))
$$;

/** Moves a shared goal to COMPLETED when every plan is done, and back when one is not. True when it was just finished. */
create function private.team_goal_sync(p_goal bigint) returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  v_total integer;
  v_done integer;
  v_rows integer;
begin
  select count(*), count(*) filter (where private.team_plan_done(t.id, t.who, t.assignee))
    into v_total, v_done from public.team_plans t where t.team_goal_id = p_goal;
  if v_total > 0 and v_done = v_total then
    update public.team_goals set status = 'COMPLETED', completed_at = now() where id = p_goal and status = 'ACTIVE';
    get diagnostics v_rows = row_count;
    return v_rows > 0;
  end if;
  update public.team_goals set status = 'ACTIVE', completed_at = null where id = p_goal and status = 'COMPLETED';
  return false;
end $$;

/** Posts "<name> started a shared goal" and the like into the chat. Returns the message id, for the push. */
create function private.team_note(p_partnership bigint, p_body text) returns bigint
language sql security definer set search_path = '' as $$
  insert into public.partner_messages (partnership_id, sender_id, kind, body)
  values (p_partnership, auth.uid(), 'TEAM', left(p_body, 1000)) returning id
$$;

/** The words for a challenge: "each of us finishes 10 plans". */
create function private.challenge_text(p_kind text, p_target integer, p_title text) returns text
language sql immutable set search_path = '' as $$
  select case p_kind
    when 'EACH_PLANS' then format('each of us finishes %s plan%s', p_target, case when p_target = 1 then '' else 's' end)
    when 'TOTAL_PLANS' then format('together we finish %s plan%s', p_target, case when p_target = 1 then '' else 's' end)
    when 'CHAT_DAYS' then format('we both chat on %s day%s', p_target, case when p_target = 1 then '' else 's' end)
    else format('each of us does “%s” on %s day%s', p_title, p_target, case when p_target = 1 then '' else 's' end) end
$$;

/** Days in a week (UTC) both partners sent a message. */
create function private.chat_days_in_week(p_partnership bigint, p_monday date) returns date[]
language sql stable security definer set search_path = '' as $$
  select coalesce(array_agg(x.day order by x.day), '{}') from (
    select (created_at at time zone 'UTC')::date as day from public.partner_messages
    where partnership_id = p_partnership and kind in ('TEXT', 'CHEER', 'IMAGE', 'VIDEO')
      and created_at >= (p_monday::timestamp at time zone 'UTC') and created_at < ((p_monday + 7)::timestamp at time zone 'UTC')
    group by 1 having count(distinct sender_id) >= 2) as x
$$;

/** A challenge with where each partner stands: me, them (counts), the days behind them, and whether it is won. */
create function private.challenge_json(c public.partner_challenges, p_me uuid, p_them uuid) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_me integer;
  v_them integer;
  v_won boolean;
  v_days date[] := '{}';
  v_me_days date[] := '{}';
  v_them_days date[] := '{}';
begin
  if c.kind in ('EACH_PLANS', 'TOTAL_PLANS') then
    v_me := private.plans_done_in_week(p_me, c.week_start);
    v_them := private.plans_done_in_week(p_them, c.week_start);
    v_won := (case when c.kind = 'EACH_PLANS' then v_me >= c.target and v_them >= c.target else v_me + v_them >= c.target end);
  elsif c.kind = 'CHAT_DAYS' then
    v_days := private.chat_days_in_week(c.partnership_id, c.week_start);
    v_me := coalesce(array_length(v_days, 1), 0); v_them := v_me;
    v_won := v_me >= c.target;
  else
    select coalesce(array_agg(on_date order by on_date) filter (where user_id = p_me), '{}'),
           coalesce(array_agg(on_date order by on_date) filter (where user_id = p_them), '{}')
      into v_me_days, v_them_days from public.challenge_checkins where challenge_id = c.id;
    v_me := coalesce(array_length(v_me_days, 1), 0); v_them := coalesce(array_length(v_them_days, 1), 0);
    v_won := v_me >= c.target and v_them >= c.target;
  end if;
  return jsonb_build_object('id', c.id, 'kind', c.kind, 'target', c.target, 'title', c.title, 'week_start', c.week_start,
    'text', private.challenge_text(c.kind, c.target, c.title), 'set_by_me', c.set_by = p_me,
    'me', v_me, 'them', v_them, 'won', v_won,
    'days', to_jsonb(v_days), 'me_days', to_jsonb(v_me_days), 'them_days', to_jsonb(v_them_days));
end $$;

create function private.partner_of(p public.partnerships) returns uuid
language sql stable set search_path = '' as $$
  select case when p.inviter_id = auth.uid() then p.invitee_id else p.inviter_id end
$$;

