-- AuraGoal on Supabase, part 5: what two partners do together. Run after partner_sharing.sql.
--   * Shared goals: one goal two partners own together, for a week, a month or a year. Each plan is done together
--     (either of them ticks it), by each of them (both tick their own part), or by one of them.
--   * A weekly challenge: either partner sets one for the week, and they win or lose it as a team.
-- Both belong to a partnership and go when it does. The tables have no grants: the app goes through the functions at
-- the bottom, which check that the caller is one of the two partners. Weeks run Monday to Sunday in UTC, like the
-- scoreboard and the chat streak.

-- "Medo started a shared goal", "Harriet set this week's challenge" and the like appear in the chat
alter table public.partner_messages drop constraint partner_messages_kind_check;
alter table public.partner_messages add constraint partner_messages_kind_check
  check (kind in ('TEXT', 'CHEER', 'NUDGE', 'IMAGE', 'VIDEO', 'TEAM'));

create table public.team_goals (
  id             bigint generated by default as identity primary key,
  partnership_id bigint not null references public.partnerships (id) on delete cascade,
  created_by     uuid not null references auth.users (id) on delete cascade,
  title          text not null check (char_length(btrim(title)) between 1 and 255),
  emoji          text not null default '🎯' check (char_length(emoji) between 1 and 8),
  why            text check (char_length(why) <= 500),     -- why the two of you want it
  timeframe      text not null default 'MONTHLY' check (timeframe in ('WEEKLY', 'MONTHLY', 'YEARLY')),
  due_date       date not null check (due_date between '2000-01-01' and '2100-12-31'),
  status         text not null default 'ACTIVE' check (status in ('ACTIVE', 'COMPLETED', 'ARCHIVED')),
  completed_at   timestamptz,
  created_at     timestamptz not null default now()
);
create index idx_team_goals_partnership on public.team_goals (partnership_id, status);

create table public.team_plans (
  id           bigint generated by default as identity primary key,
  team_goal_id bigint not null references public.team_goals (id) on delete cascade,
  task         text not null check (char_length(btrim(task)) between 1 and 500),
  who          text not null default 'TOGETHER' check (who in ('TOGETHER', 'EACH', 'ONE')),
  assignee     uuid references auth.users (id) on delete cascade,   -- ONE: the partner it is for
  position     smallint not null default 0,
  check ((who = 'ONE') = (assignee is not null))
);
create index idx_team_plans_goal on public.team_plans (team_goal_id);

create table public.team_plan_marks (                   -- who ticked a shared plan, and when (for the scoreboard)
  team_plan_id bigint not null references public.team_plans (id) on delete cascade,
  user_id      uuid not null references auth.users (id) on delete cascade,
  done_at      timestamptz not null default now(),
  primary key (team_plan_id, user_id)
);
create index idx_team_marks_user on public.team_plan_marks (user_id, done_at);

create table public.partner_challenges (
  id             bigint generated by default as identity primary key,
  partnership_id bigint not null references public.partnerships (id) on delete cascade,
  week_start     date not null,                            -- the Monday (UTC)
  kind           text not null check (kind in ('EACH_PLANS', 'TOTAL_PLANS', 'CHAT_DAYS', 'HABIT')),
  target         smallint not null check (target between 1 and 200),
  title          text check (char_length(title) <= 120),   -- HABIT: what both of you do, e.g. "No sugar"
  set_by         uuid not null references auth.users (id) on delete cascade,
  created_at     timestamptz not null default now(),
  unique (partnership_id, week_start)
);

create table public.challenge_checkins (                -- HABIT: the days each partner did it
  challenge_id bigint not null references public.partner_challenges (id) on delete cascade,
  user_id      uuid not null references auth.users (id) on delete cascade,
  on_date      date not null,
  primary key (challenge_id, user_id, on_date)
);

alter table public.team_goals enable row level security;
alter table public.team_plans enable row level security;
alter table public.team_plan_marks enable row level security;
alter table public.partner_challenges enable row level security;
alter table public.challenge_checkins enable row level security;
revoke all on public.team_goals, public.team_plans, public.team_plan_marks, public.partner_challenges, public.challenge_checkins
  from public, anon, authenticated;

